def client_price(amount, dcc: bool):
    try:
        net = float(amount)
    except (TypeError, ValueError):
        return amount
    # Half up, the same as Math.round in lib/availability.mjs (Python's round() is half-to-even).
    if not net or dcc:
        return int(math.floor(net + 0.5))
    return int(math.floor(net * (1 + MARKUP_PERCENT / 100) + 0.5))


