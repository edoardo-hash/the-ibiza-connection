def write(path: str, content: str) -> None:
    target = STAGE / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")


def write_chat_data() -> None:
    """lib/chat-data.json for the AI concierge (api/chat): only what the public site shows —
    client prices (markup applied, none on DCC), booked dates, area distances. No net prices,
    no owners, no exact positions, no uuids."""
    villas = []
    for v in VILLAS:
        info = area_info(v) or {}
        villas.append({
            "slug": v["slug"], "name": v["name"], "area": v["area"], "district": v["region_name"],
            "bedrooms": v["bedrooms"], "bathrooms": v["bathrooms"], "sleeps": v["sleeps"],
            "from_week": v.get("price_from") or None, "to_week": v.get("price_to") or None,
            "min_nights": v.get("min_nights") or 7, "short_stays": bool(v.get("short_stays")),
            "check_in_days": v.get("check_in_days") or "", "licence": display_licence(v),
            "summary": v.get("summary") or "", "audience": v.get("audience") or [],
            "amenities": v.get("amenities") or [],
            "nearby": {k: info.get(k) for k in ("airportKm", "townKm", "beach", "nearTown", "supermarket",
                                               "restaurants", "sights") if info.get(k) is not None},
            "rates": [[r["from"], r["to"], r["night"], r.get("min_nights") or 0, strict_day(r.get("checkin"))] for r in PRICES.get(v["slug"], [])],
            "strict_day": strict_day(v.get("check_in_days")),
            "booked": _BUSY["busy"].get(v["v_uuid"].lower(), []),
        })
    data = {
        "updated": _BUSY.get("fetched_at", ""),
        "site": SITE_URL,
        "whatsapp": SITE.get("whatsapp", ""),
        "email": SITE.get("email", ""),
        "price_match": (SETTINGS.get("price_match") or {}).get("text", ""),
        "villas": villas,
    }
    (ROOT / "lib" / "chat-data.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")


def main() -> None:
    # Build into a staging folder, then swap it into place. This keeps the
    # running site complete while a rebuild is in progress.
    if STAGE.exists():
        shutil.rmtree(STAGE)
    STAGE.mkdir(parents=True)

    # Assets
    shutil.copytree(ASSETS, STAGE / "assets")

    write(STAYS_URL.lstrip("/"), STAYS_JSON)
    write_chat_data()

    # Core pages
    write("index.html", build_home())
    write("villas/index.html", build_villas())
    write("destinations/index.html", build_destinations())
    for region in DESTINATIONS["regions"]:
        write(f"destinations/{region['slug']}/index.html", build_destination(region))
    write("journal/index.html", build_journal())
    for post in JOURNAL["posts"]:
        write(f"journal/{post['slug']}/index.html", build_article(post))
    for villa in VILLAS:
        write(f"villa/{villa['slug']}/index.html", build_villa(villa))

    write("about/index.html", build_content_page("about", "/about/", "about"))
    write("owners/index.html", build_content_page("owners", "/owners/", ""))
    write("experiences/index.html", build_content_page("experiences", "/experiences/", "experiences"))
    write("experiences/boat-rental/index.html", build_content_page("boat-rental", "/experiences/boat-rental/", "experiences"))
    write("experiences/car-hire/index.html", build_content_page("car-hire", "/experiences/car-hire/", "experiences"))
    write("experiences/concierge/index.html", build_content_page("concierge", "/experiences/concierge/", "experiences"))
    write("contact/index.html", build_contact())
    write("privacy/index.html", build_legal("privacy", "/privacy/"))
    write("terms/index.html", build_legal("terms", "/terms/"))
    write("404.html", build_404())

    # Machine-readable
    write("sitemap.xml", build_sitemap())
    write(
        "robots.txt",
        f"User-agent: *\nAllow: /\n\nSitemap: {SITE_URL}/sitemap.xml\n",
    )
    write(
        "site.webmanifest",
        json.dumps(
            {
                "name": SITE["name"],
                "short_name": SITE["short_name"],
                "icons": [{"src": "/assets/img/apple-touch-icon.png", "sizes": "180x180", "type": "image/png"}],
                "theme_color": "#f6f1e7",
                "background_color": "#f6f1e7",
                "display": "standalone",
                "start_url": "/",
            },
            indent=2,
        ),
    )

    old = ROOT / ".dist-old"
    if old.exists():
        shutil.rmtree(old)
    if DIST.exists():
        DIST.rename(old)
    STAGE.rename(DIST)
    if old.exists():
        shutil.rmtree(old, ignore_errors=True)

    pages = sum(1 for _ in DIST.rglob("index.html"))
    size = sum(f.stat().st_size for f in DIST.rglob("*") if f.is_file())
    print(f"✓ {pages} pages · {len(VILLAS)} villas · {len(JOURNAL['posts'])} journal stories")
    print(f"✓ dist/ — {size / 1024 / 1024:.1f} MB")
    print(f"  {META['fetched_at']} · {META['published']} published of {META['available_in_account']} in the account")


if __name__ == "__main__":
    main()
