def villa_image(villa: dict, index: int = 0) -> dict:
    images = villa.get("images") or []
    if index < len(images):
        return images[index]
    if images:
        return images[0]
    return {"base": None, "url": villa.get("image", ""), "width": 1400, "height": 933, "colour": "#d8d1c4"}


def image_tag(image: dict, alt: str, sizes: str, cls: str = "", loading: str = "lazy", priority: bool = False) -> str:
    alt_attr = esc(alt)
    attrs = [f'alt="{alt_attr}"', f'class="{cls}"' ] if cls else [f'alt="{alt_attr}"']
    if loading:
        attrs.append(f'loading="{loading}"')
    attrs.append('decoding="async"')
    if priority:
        attrs.append('fetchpriority="high"')
    base = image.get("base")
    if base:
        src = f"/assets/{base}-800.webp"
        srcset = ", ".join(f"/assets/{base}-{w}.webp {w}w" for w in (400, 800, 1400))
        attrs += [
            f'src="{src}"',
            f'srcset="{srcset}"',
            f'sizes="{sizes}"',
            f'width="{image.get("width", 1400)}"',
            f'height="{image.get("height", 933)}"',
        ]
    else:
        attrs += [f'src="{esc(image.get("url", ""))}"', 'width="1400"', 'height="933"']
    return "<img " + " ".join(attrs) + ">"


def display_licence(villa: dict) -> str:
    """The tourist licence as the official register writes it when the 4 digits are
    verified (data/licence-check.json), otherwise as entered in IMpulse."""
    check = villa.get("licence_check") or {}
    if check.get("status") in ("verified", "format_differs") and check.get("register_licence"):
        return check["register_licence"]
    lic = (villa.get("license") or "").strip()
    return "" if lic.upper() == "TBA" else lic


